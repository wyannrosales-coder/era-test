/**
 * Bundles the assistant's knowledge base (knowledge/*.md, copied from epiisod.com, plus the
 * booking catalogue) into api/_knowledge.ts, which the /api/chat function sends to Claude.
 * Run `npm run knowledge` after editing anything in knowledge/.
 */
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const dir = join(root, 'knowledge');
// The catalogue goes last: the instructions call it the authority on prices and terms
const ORDER = ['properties.md', 'faqs.md', 'promotions.md', 'policies.md', 'company.md', 'rooms.md'];
const files = readdirSync(dir)
  .filter((f) => f.endsWith('.md'))
  .sort((a, b) => (ORDER.indexOf(a) + 1 || 50) - (ORDER.indexOf(b) + 1 || 50) || a.localeCompare(b));

const text = files
  .map((f) => `<document name="${f}">\n${readFileSync(join(dir, f), 'utf8').trim()}\n</document>`)
  .join('\n\n');

writeFileSync(
  join(root, 'api', '_knowledge.ts'),
  `// Generated by tools/build-knowledge.mjs from knowledge/*.md. Do not edit: run \`npm run knowledge\`.\nexport const KNOWLEDGE = ${JSON.stringify(text)};\n`,
);
console.log(`knowledge: ${files.length} files, ${text.length.toLocaleString()} characters → api/_knowledge.ts`);
