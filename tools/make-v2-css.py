#!/usr/bin/env python3
"""Builds dist/assets/epiisod-v2-auto.css: for every rule in the site's own stylesheets that uses the chocolate / sand
brand colours, a copy under html[data-ep-ver="2"] with the design-system colours swapped in. Re-run after changing those
stylesheets:  python3 tools/make-v2-css.py"""
import re, os
A = os.path.join(os.path.dirname(__file__), '..', 'dist', 'assets')
FILES = ['epiisod-app.css', 'epiisod-badge.css', 'epiisod-facade.css', 'epiisod-location.css', 'epiisod-nav.css', 'epiisod-reveal.css',
         'epiisod-ring.css', 'epiisod-rooms.css', 'epiisod-smart-demo.css', 'epiisod-story.css', 'epiisod-theme.css']
SWAP = [(re.compile(r'#24120c', re.I), '#212529'), (re.compile(r'#d0a77f', re.I), '#896d42'), (re.compile(r'#d7c5a9', re.I), '#dcd7d3'),
        (re.compile(r'rgba\(\s*36\s*,\s*18\s*,\s*12\s*,'), 'rgba(33,37,41,'), (re.compile(r'rgba\(\s*208\s*,\s*167\s*,\s*127\s*,'), 'rgba(137,109,66,')]
EXTRA = {'epiisod-badge.css': [(re.compile(r'rgba\(\s*246\s*,\s*241\s*,\s*234\s*,'), 'rgba(57,29,19,'), (re.compile(r'#f6f1ea', re.I), '#391d13'), (re.compile(r'#f4f2f0', re.I), '#391d13')]}
PRE = 'html[data-ep-ver="2"]'

def strip(c): return re.sub(r'/\*.*?\*/', '', c, flags=re.S)
def parse(s, i=0):
    nodes = []
    while i < len(s):
        j = i
        while j < len(s) and s[j] not in '{};': j += 1
        if j >= len(s): break
        if s[j] == '}': return nodes, j + 1
        if s[j] == ';': i = j + 1; continue
        head = s[i:j].strip()
        if head.startswith('@') and re.match(r'@(media|supports|layer|container)', head):
            kids, i = parse(s, j + 1); nodes.append(('at', head, kids))
        else:
            k = s.find('}', j)
            if head.startswith('@'):        # keyframes / font-face: skip (keyframes may nest)
                depth = 1; k = j + 1
                while depth and k < len(s):
                    depth += (s[k] == '{') - (s[k] == '}'); k += 1
                i = k; continue
            nodes.append(('rule', head, s[j + 1:k])); i = k + 1
    return nodes, i
def split_sel(sel):
    out, d, cur = [], 0, ''
    for ch in sel:
        if ch in '([': d += 1
        if ch in ')]': d -= 1
        if ch == ',' and d == 0: out.append(cur.strip()); cur = ''
        else: cur += ch
    out.append(cur.strip()); return [x for x in out if x]
def prefix(sel):
    if sel.startswith(':root') or sel.startswith('@'): return None
    if re.match(r'^html\b', sel): return PRE + sel[4:]
    return PRE + ' ' + sel
def decls(body):
    out, cur, d = [], '', 0
    for ch in body:
        if ch == '(': d += 1
        if ch == ')': d -= 1
        if ch == ';' and d == 0: out.append(cur); cur = ''
        else: cur += ch
    if cur.strip(): out.append(cur)
    return [x.strip() for x in out if x.strip()]
def emit(nodes, ind='', extra=()):
    out = []
    for n in nodes:
        if n[0] == 'at':
            inner = emit(n[2], ind + '  ', extra)
            if inner: out.append(ind + n[1] + ' {\n' + '\n'.join(inner) + '\n' + ind + '}')
        else:
            ch = []
            for d in decls(n[2]):
                nd = d
                for rx, to in list(SWAP) + list(extra): nd = rx.sub(to, nd)
                if nd != d and ':' in nd: ch.append(nd)
            sels = [p for p in (prefix(s) for s in split_sel(n[1])) if p]
            if ch and sels: out.append(ind + ', '.join(sels) + ' { ' + '; '.join(ch) + '; }')
    return out
res = ['/* Generated by tools/make-v2-css.py: the site stylesheets\' chocolate and sand colours, swapped for the design-system scheme in version 2. */']
for f in FILES:
    s = strip(open(os.path.join(A, f)).read())
    nodes, _ = parse(s)
    r = emit(nodes, '', EXTRA.get(f, ()))
    res.append('/* ' + f + ' */'); res.extend(r)
    print(f, len(r))
open(os.path.join(A, 'epiisod-v2-auto.css'), 'w').write('\n'.join(res) + '\n')
